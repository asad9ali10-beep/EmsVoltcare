// Helper to generate 6 months of historical bills for each consumer
export function generateInitialBills(): Bill[] {
  const months = [
    { name: 'May 2026', issue: '2026-05-02', due: '2026-05-16', paid: '2026-05-10', status: 'Paid' as const },
    { name: 'June 2026', issue: '2026-06-02', due: '2026-06-16', paid: '2026-06-12', status: 'Paid' as const },
    { name: 'July 2026', issue: '2026-07-02', due: '2026-07-16', paid: '2026-07-14', status: 'Paid' as const },
    { name: 'August 2026', issue: '2026-08-02', due: '2026-08-16', paid: '2026-08-11', status: 'Paid' as const },
    { name: 'September 2026', issue: '2026-09-02', due: '2026-09-16', paid: '2026-09-15', status: 'Paid' as const },
    { name: 'October 2026', issue: '2026-10-02', due: '2026-10-16', paid: undefined, status: 'Unpaid' as const },
  ];

  const bills: Bill[] = [];
  let billCounter = 5001;

  INITIAL_CONSUMERS.forEach((consumer, cIndex) => {
    // Base reading starting point
    let baseReading = 1200 + cIndex * 350;

    months.forEach((m, mIndex) => {
      // Seasonal consumption: June/July higher due to AC usage in Pakistan summers
      const monthlyUnits = mIndex === 1 || mIndex === 2 ? 380 + (cIndex * 40) : 210 + (cIndex * 35);
      const prevReading = baseReading;
      const currReading = baseReading + monthlyUnits;
      baseReading = currReading;

      const charges = calculateBillCharges(prevReading, currReading);
      
      // Let c2 have Overdue bill for October to show Overdue status
      let currentStatus: 'Paid' | 'Unpaid' | 'Overdue' = m.status;
      if (consumer.id === 'c2' && mIndex === 5) {
        currentStatus = 'Overdue';
      }
      // Let c3 have Paid October bill to show variance
      if (consumer.id === 'c3' && mIndex === 5) {
        currentStatus = 'Paid';
      }

      const billId = `bill-${billCounter}`;
      const isPaid = currentStatus === 'Paid';

      bills.push({
        id: billId,
        billNumber: `VC-260${mIndex + 5}-${billCounter}`,
        consumerId: consumer.id,
        consumerName: consumer.name,
        consumerNumber: consumer.consumerNumber || `04-99887-${billCounter}`,
        meterNumber: consumer.meterNumber || `MTR-${billCounter}`,
        billingMonth: m.name,
        issueDate: m.issue,
        dueDate: m.due,
        previousReading: prevReading,
        currentReading: currReading,
        ...charges,
        status: currentStatus,
        paidDate: isPaid ? (m.paid || '2026-10-11') : undefined,
        paymentMethod: isPaid ? (mIndex % 2 === 0 ? 'JazzCash' : 'Easypaisa') : undefined,
        transactionId: isPaid ? `TXN-88${billCounter}${mIndex}` : undefined,
      });

      billCounter++;
    });
  });

  return bills;
}

export const INITIAL_BILLS: Bill[] = generateInitialBills();

